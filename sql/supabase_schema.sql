-- 2. PUBLIC INSERT POLICIES (Storefront Guest Submissions with Strict Validation)
-- NOTE: Orders must ONLY be placed through the authoritative backend API (/api/orders)
-- where prices and Paystack transactions are cryptographically verified.
-- Direct anon insertion into orders is disallowed to prevent payment tampering.

CREATE POLICY "Public insert catering_bookings" ON public.catering_bookings FOR INSERT TO anon
  WITH CHECK (
    guest_count > 0
    AND customer_name IS NOT NULL
    AND length(trim(customer_name)) >= 2
    AND phone IS NOT NULL
    AND length(trim(phone)) >= 7
    AND outlet IN ('Adabraka', 'Dzorwulu')
  );

CREATE POLICY "Public insert training_applications" ON public.training_applications FOR INSERT TO anon
  WITH CHECK (
    full_name IS NOT NULL
    AND length(trim(full_name)) >= 2
    AND phone IS NOT NULL
    AND length(trim(phone)) >= 7
    AND email IS NOT NULL
    AND length(trim(email)) >= 5
    AND program IS NOT NULL
  );

CREATE POLICY "Public insert contact_messages" ON public.contact_messages FOR INSERT TO anon
  WITH CHECK (
    full_name IS NOT NULL
    AND length(trim(full_name)) >= 2
    AND message IS NOT NULL
    AND length(trim(message)) >= 2
  );

CREATE POLICY "Public insert ratings" ON public.ratings FOR INSERT TO anon
  WITH CHECK (
    rating BETWEEN 1 AND 5
    AND customer_name IS NOT NULL
    AND length(trim(customer_name)) >= 2
    AND outlet IN ('Adabraka', 'Dzorwulu')
  );

