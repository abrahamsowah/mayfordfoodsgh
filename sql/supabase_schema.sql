-- Atomic visitor counter increment function for Supabase RPC
CREATE OR REPLACE FUNCTION public.increment_visitor_counter()
RETURNS BIGINT
LANGUAGE sql
SECURITY DEFINER
SET search_path = public
AS $$
  UPDATE public.visitor_counter
  SET total_visitors = total_visitors + 1
  WHERE id = 1
  RETURNING total_visitors;
$$;

-- Secure customer order tracking RPC (requires matching ID and last 4 phone digits, returns non-sensitive payload)
CREATE OR REPLACE FUNCTION public.track_customer_order(p_order_id BIGINT, p_phone_last4 TEXT)
RETURNS TABLE (
  id BIGINT,
  customer_name VARCHAR(255),
  outlet VARCHAR(100),
  order_type VARCHAR(100),
  food_item VARCHAR(255),
  quantity INTEGER,
  order_details TEXT,
  delivery_zone VARCHAR(120),
  delivery_fee NUMERIC(10, 2),
  total NUMERIC(10, 2),
  payment_method VARCHAR(50),
  payment_status VARCHAR(50),
  status VARCHAR(50),
  order_date TIMESTAMPTZ
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  RETURN QUERY
  SELECT
    o.id,
    o.customer_name,
    o.outlet,
    o.order_type,
    o.food_item,
    o.quantity,
    o.order_details,
    o.delivery_zone,
    o.delivery_fee,
    o.total,
    o.payment_method,
    o.payment_status,
    o.status,
    o.order_date
  FROM public.orders o
  WHERE o.id = p_order_id
    AND RIGHT(regexp_replace(o.phone, '\D', '', 'g'), 4) = RIGHT(regexp_replace(p_phone_last4, '\D', '', 'g'), 4);
END;
$$;

